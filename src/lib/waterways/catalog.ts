export function factForName(name: string | undefined | null): FamousFact | undefined {
  if (!name) return undefined;
  const n = normalizeName(name);
  const direct = INDEX.get(n);
  if (direct) return direct;
  for (const [alias, fact] of INDEX) {
    if (n.includes(alias) || alias.includes(n)) return fact;
  }
  return undefined;
}
